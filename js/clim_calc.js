/* Радиация (табл. 13.1, 13.2) на широте lat — линейно между 40…68° с. ш.; за пределами — крайнее значение */
function clRad(arr, lat) {
  var L = SP131.lats;
  if (lat <= L[0]) return arr[0];
  if (lat >= L[L.length - 1]) return arr[L.length - 1];
  for (var i = 0; i < L.length - 1; i++) if (lat <= L[i + 1]) {
    var a = arr[i], b = arr[i + 1], k = (lat - L[i]) / (L[i + 1] - L[i]);
    if (a === null || b === null) return a === null ? b : a;
    return a + k * (b - a);
  }
}

