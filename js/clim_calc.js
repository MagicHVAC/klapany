/* Rтр по графе j (0…4): {v, how} */
function clRtr(cat, j, g) {
  var t = CL_T3[cat], a = t.a[j], b = t.b[j], row = t.v[j];
  if (j === 3 && g > 12000) return { v: row[6], how: 'свыше 12000 — как для 12000 (прим. 1 к табл. 3)' };
  if (a !== null) return { v: a * g + b, how: 'a·ГСОП + b = ' + String(a).replace('.', ',') + ' × ' + Math.round(g) + ' + ' + String(b).replace('.', ',') + ' (прим. 1)' };
  if (g <= CL_G[0]) return { v: row[0], how: 'ниже 1000 — значение для 1000 (допущение справочника: a, b в табл. 3 нет)' };
  if (g >= CL_G[6]) return { v: row[6], how: 'выше 12000 — значение для 12000 (допущение справочника: a, b в табл. 3 нет)' };
  for (var i = 0; i < 6; i++) if (g <= CL_G[i + 1]) {
    var k = (g - CL_G[i]) / (CL_G[i + 1] - CL_G[i]);
    return { v: row[i] + k * (row[i + 1] - row[i]), how: 'интерполяция между ' + CL_G[i] + ' и ' + CL_G[i + 1] + ' (a, b в табл. 3 — прочерк)' };
  }
}

/* ГСОП: город c (SP131.cities), тип здания bt (CL_BT), tв */
function clGsop(c, bt, tv) {
  var v = c.cold, p10 = bt[3] === 10;
  var z = p10 ? v[11] : v[9], t = p10 ? v[12] : v[10];
  if (z === null || t === null) return null;
  return { z: z, t: t, per: p10 ? 10 : 8, g: (tv - t) * z };
}

/* Энтальпия влажного воздуха, кДж/кг: d = 622·pп/(P − pп), pп = φ·pн(t); pн — Магнус (над льдом при t < 0) — справочно */
function clPs(t) { return t < 0 ? 6.112 * Math.exp(22.46 * t / (272.62 + t)) : 6.112 * Math.exp(17.62 * t / (243.12 + t)); }
function clEnth(t, phi, P) {
  var pw = phi / 100 * clPs(t), d = 622 * pw / (P - pw);
  return { i: 1.006 * t + d / 1000 * (2501 + 1.86 * t), d: d };
}

/* Радиация (табл. 13.1, 13.2) на широте lat — линейно между 40…68° с. ш.; за пределами — крайнее значение */
function clRad(arr, lat) {
  var L = SP131.lats;
  if (lat <= L[0]) return arr[0];
  if (lat >= L[L.length - 1]) return arr[L.length - 1];
  for (var i = 0; i < L.length - 1; i++) if (lat <= L[i + 1]) {
    var a = arr[i], b = arr[i + 1], k = (lat - L[i]) / (L[i + 1] - L[i]);
    if (a === null || b === null) return a === null ? b : a;
    return a + k * (b - a);
  }
}
